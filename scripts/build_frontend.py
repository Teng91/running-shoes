"""Deterministically assemble local CSS/templates and the atomic PWA asset list."""

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FRONTEND = ROOT / "frontend"
STATIC_SHELL_FILES = (
    "offline.html", "manifest.webmanifest", "favicon.svg", "icons/icon-192.png",
    "icons/icon-512.png", "icons/apple-touch-icon.png", "vendor/chart.umd.min.js",
    "vendor/marked.min.js",
)


def shell_asset_paths(manifest: dict) -> list[tuple[str, str]]:
    versioned = manifest["scripts"] + manifest["modules"] + ["styles.css"]
    return [("/", "index.html"), *[
        (f"/{name}?v={manifest['version']}", name) for name in versioned
    ], *[(f"/{name}", name) for name in STATIC_SHELL_FILES]]


def frontend_outputs() -> dict[Path, str]:
    manifest = json.loads((FRONTEND / "assets.json").read_text(encoding="utf-8"))
    version = manifest["version"]
    scripts = manifest["scripts"]
    modules = manifest["modules"]
    styles = manifest["styles"]
    assets = scripts + modules + styles
    if len(set(assets)) != len(assets):
        raise ValueError("duplicate frontend asset")
    for name in assets:
        path = (FRONTEND / name).resolve()
        if FRONTEND not in path.parents or not path.is_file():
            raise ValueError(f"invalid or missing frontend source: {name}")
    templates = FRONTEND / "templates"
    html = (templates / "index.html").read_text(encoding="utf-8")
    html = re.sub(
        r"<!-- include:([\w.-]+\.html) -->",
        lambda match: (templates / match[1]).read_text(encoding="utf-8").rstrip(),
        html,
    )
    html = html.replace(
        "<!-- app-scripts -->",
        "\n".join(f'<script src="/{name}?v={version}"></script>' for name in scripts),
    ).replace("{{asset_version}}", version)
    css = "/* Generated by scripts/build_frontend.py; edit frontend/css sources. */\n" + "\n".join(
        f"/* Source: {name} */\n" + (FRONTEND / name).read_text(encoding="utf-8").rstrip() + "\n"
        for name in styles
    )
    shell = ["  '/',"] + [f"  versioned('/{name}')," for name in scripts + modules + ["styles.css"]]
    shell += [
        f"  '/{name}',"
        for name in STATIC_SHELL_FILES
    ]
    worker = (templates / "service-worker.js").read_text(encoding="utf-8")
    worker = worker.replace("{{shell_assets}}", "\n".join(shell))
    worker = worker.replace("{{asset_version}}", version).replace(
        "{{cache_name}}", manifest["cache_name"]
    )
    if "{{" in html or "{{" in worker:
        raise ValueError("unresolved frontend template marker")
    return {
        FRONTEND / "index.html": html,
        FRONTEND / "styles.css": css,
        FRONTEND / "service-worker.js": worker,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="regenerate checked-in static outputs")
    parser.add_argument("--check", action="store_true", help="verify generated outputs (default)")
    args = parser.parse_args()
    drift = []
    for path, expected in frontend_outputs().items():
        if args.write:
            path.write_text(expected, encoding="utf-8", newline="\n")
        elif path.read_text(encoding="utf-8") != expected:
            drift.append(path.name)
    if drift:
        print(
            f"Frontend assets out of date: {', '.join(drift)}. Run python3 scripts/build_frontend.py --write"
        )
        return 1
    print(
        "Frontend assets generated." if args.write else "Generated frontend assets match sources."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
